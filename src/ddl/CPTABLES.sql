CREATE TABLESPACE CPFEETS IN CPDB
  USING STOGROUP CPSG01
  SEGSIZE 32
  LOCKSIZE PAGE
  BUFFERPOOL BP1
  CLOSE NO;

CREATE TABLESPACE CPADJTS IN CPDB
  USING STOGROUP CPSG01
  SEGSIZE 32
  LOCKSIZE ROW
  BUFFERPOOL BP1
  CLOSE NO;

CREATE TABLESPACE CPAUDTS IN CPDB
  USING STOGROUP CPSG01
  SEGSIZE 64
  LOCKSIZE PAGE
  BUFFERPOOL BP2
  CLOSE NO;

CREATE TABLE CP_FEE_SCHEDULE
  (NETWORK        CHAR(4)        NOT NULL,
   PRODUCT        CHAR(4)        NOT NULL,
   MCC_CLASS      CHAR(2)        NOT NULL,
   PRESENCE       CHAR(1)        NOT NULL,
   RATE           DECIMAL(5,4)   NOT NULL,
   PER_ITEM       DECIMAL(5,2)   NOT NULL,
   MAX_FEE        DECIMAL(7,2)   NOT NULL WITH DEFAULT 0,
   EFF_DATE       DATE           NOT NULL,
   END_DATE       DATE,
   UPDATED_BY     CHAR(8)        NOT NULL,
   UPDATED_TS     TIMESTAMP      NOT NULL WITH DEFAULT,
   CONSTRAINT PK_FEE_SCHEDULE
     PRIMARY KEY (NETWORK, PRODUCT, MCC_CLASS, PRESENCE, EFF_DATE),
   CONSTRAINT CK_FEE_PRESENCE
     CHECK (PRESENCE IN ('P', 'N', '*')),
   CONSTRAINT CK_FEE_RATE
     CHECK (RATE >= 0 AND PER_ITEM >= 0 AND MAX_FEE >= 0),
   CONSTRAINT CK_FEE_DATES
     CHECK (END_DATE IS NULL OR END_DATE > EFF_DATE))
  IN CPDB.CPFEETS;

CREATE UNIQUE INDEX CPFEEX1
  ON CP_FEE_SCHEDULE
  (NETWORK, PRODUCT, MCC_CLASS, PRESENCE, EFF_DATE)
  CLUSTER;

CREATE TABLE CP_ADJUSTMENT
  (ADJ_ID         INTEGER        NOT NULL
                  GENERATED ALWAYS AS IDENTITY
                  (START WITH 1000001, INCREMENT BY 1, CACHE 20),
   ACCT_NUM       CHAR(12)       NOT NULL,
   ADJ_TYPE       CHAR(1)        NOT NULL,
   AMOUNT         DECIMAL(11,2)  NOT NULL,
   REASON_CODE    CHAR(4)        NOT NULL,
   STATUS         CHAR(1)        NOT NULL,
   MAKER_ID       CHAR(8)        NOT NULL,
   MAKER_TS       TIMESTAMP      NOT NULL,
   CHECKER_ID     CHAR(8),
   CHECKER_TS     TIMESTAMP,
   CONSTRAINT PK_ADJUSTMENT PRIMARY KEY (ADJ_ID),
   CONSTRAINT CK_ADJ_TYPE   CHECK (ADJ_TYPE IN ('D', 'C')),
   CONSTRAINT CK_ADJ_STATUS CHECK (STATUS IN ('P', 'A', 'R')),
   CONSTRAINT CK_ADJ_AMOUNT CHECK (AMOUNT > 0),
   CONSTRAINT CK_ADJ_DUAL   CHECK (CHECKER_ID IS NULL
                                   OR CHECKER_ID <> MAKER_ID))
  IN CPDB.CPADJTS;

CREATE UNIQUE INDEX CPADJX1
  ON CP_ADJUSTMENT (ADJ_ID)
  CLUSTER;

CREATE INDEX CPADJX2
  ON CP_ADJUSTMENT (ACCT_NUM, STATUS, MAKER_TS DESC);

CREATE TABLE CP_AUDIT_LOG
  (AUDIT_TS       TIMESTAMP      NOT NULL WITH DEFAULT,
   USER_ID        CHAR(8)        NOT NULL,
   ACCT_NUM       CHAR(12)       NOT NULL,
   ACTION         CHAR(8)        NOT NULL,
   REF_ID         INTEGER,
   BEFORE_BAL     DECIMAL(11,2),
   AFTER_BAL      DECIMAL(11,2))
  IN CPDB.CPAUDTS;

CREATE INDEX CPAUDX1
  ON CP_AUDIT_LOG (ACCT_NUM, AUDIT_TS DESC)
  CLUSTER;
